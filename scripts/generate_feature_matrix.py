#!/usr/bin/env python3
"""Generate docs/COMMERCIAL_FEATURE_MATRIX.md from the edition catalogue in a
migrated database (plans / plan_features / plan_limits) — the same data the
API enforces, so the matrix cannot drift from the product.

Usage: python scripts/generate_feature_matrix.py --dsn postgresql://hms:<pw>@host:port/db
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import psycopg2

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps" / "api"))
from app.entitlements import FEATURES, LIMITS  # noqa: E402

OUT = ROOT / "docs" / "COMMERCIAL_FEATURE_MATRIX.md"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dsn", required=True)
    dsn = ap.parse_args().dsn.replace("postgresql+psycopg2://", "postgresql://")
    with psycopg2.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute("SELECT id, code, name, tier, trial_days, price_monthly_paise, "
                    "price_annual_paise, is_public, description FROM plans ORDER BY tier")
        plans = cur.fetchall()
        cur.execute("SELECT plan_id, feature_key FROM plan_features")
        feats = {(p, f) for p, f in cur.fetchall()}
        cur.execute("SELECT plan_id, limit_key, limit_value FROM plan_limits")
        limits = {(p, k): v for p, k, v in cur.fetchall()}

    def price(v):
        return "not configured" if v is None else f"₹{v / 100:,.2f}"

    lines = [
        "# Commercial feature matrix — editions",
        "",
        "> Generated by `scripts/generate_feature_matrix.py` from the edition catalogue",
        "> seeded by migration 0011 — the data the API enforces (`app/entitlements.py`).",
        "> Prices are **configured by the platform owner** in the console; a fresh",
        "> installation has none (no prices are hard-coded). Features listed here are",
        "> *entitlement switches*: several (AI, ABDM, FHIR, OT, emergency, TPA, comms",
        "> delivery) are on the roadmap and not yet implemented — see TASKS.md.",
        "",
        "## Editions",
        "",
        "| Tier | Code | Edition | Trial | Monthly | Annual | Public |",
        "|---|---|---|---|---|---|---|",
    ]
    for _id, code, name, tier, trial, pm, pa, public, _d in plans:
        lines.append(f"| {tier} | `{code}` | {name} | {trial} days | {price(pm)} | "
                     f"{price(pa)} | {'yes' if public else 'sales-led'} |")
    lines += ["", "## Features", "", "| Feature | " + " | ".join(p[2] for p in plans) + " |",
              "|---|" + "---|" * len(plans)]
    for key, label in FEATURES.items():
        cells = ["✅" if (p[0], key) in feats else "—" for p in plans]
        lines.append(f"| {label} (`{key}`) | " + " | ".join(cells) + " |")
    lines += ["", "## Limits (blank value = unlimited)", "",
              "| Limit | " + " | ".join(p[2] for p in plans) + " |",
              "|---|" + "---|" * len(plans)]
    for key, label in LIMITS.items():
        cells = []
        for p in plans:
            v = limits.get((p[0], key), None)
            cells.append("unlimited" if v is None else f"{v:,}")
        lines.append(f"| {label} (`{key}`) | " + " | ".join(cells) + " |")
    lines += ["", "## Descriptions", ""]
    lines += [f"- **{p[2]}** — {p[8]}" for p in plans]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(plans)} editions, {len(FEATURES)} features")


if __name__ == "__main__":
    main()
